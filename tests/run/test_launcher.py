# write_local
# ---------------------------------------------------------------------------

class TestWriteLocal:
    """A background-parallel launcher for this machine."""

    def test_is_valid_bash(self, runs: list[Run], tmp_path: Path) -> None:
        _check_syntax(write_local(runs, tmp_path / "run_all.sh"))

    def test_returns_an_executable_script(
        self, runs: list[Run], tmp_path: Path
    ) -> None:
        path = write_local(runs, tmp_path / "run_all.sh")

        assert path.is_file()
        assert path.stat().st_mode & 0o111

    def test_lists_every_run_by_absolute_path(
        self, runs: list[Run], tmp_path: Path
    ) -> None:
        text = write_local(runs, tmp_path / "run_all.sh").read_text()

        for one in runs:
            assert str(one.workdir) in text
            assert one.workdir.is_absolute()

    def test_has_the_done_guard(
        self, runs: list[Run], tmp_path: Path
    ) -> None:
        """Re-running the script must resume, not redo."""
        text = write_local(runs, tmp_path / "run_all.sh").read_text()

        assert 'compgen -G "$RUN_DIR/output/*_DONE"' in text

    def test_invokes_an_absolute_namelist_path(
        self, runs: list[Run], tmp_path: Path
    ) -> None:
        text = write_local(runs, tmp_path / "run_all.sh").read_text()

        assert '"$EXE" "$RUN_DIR/inputs/params.nml"' in text

    @pytest.mark.parametrize("jobs", [1, 3, 16])
    def test_jobs_caps_concurrency(
        self, runs: list[Run], tmp_path: Path, jobs: int
    ) -> None:
        path = write_local(runs, tmp_path / "run_all.sh", jobs=jobs)
        text = path.read_text()

        assert f"JOBS={jobs}" in text
        assert "while (( $(jobs -rp | wc -l) >= JOBS )); do wait -n; done" in text
        _check_syntax(path)

    def test_rejects_a_bad_job_count(
        self, runs: list[Run], tmp_path: Path
    ) -> None:
        with pytest.raises(ValueError, match="at least 1"):
            write_local(runs, tmp_path / "run_all.sh", jobs=0)

    def test_timing_file_defaults_beside_the_script(
        self, runs: list[Run], tmp_path: Path
    ) -> None:
        text = write_local(runs, tmp_path / "sub" / "run_all.sh").read_text()

        assert str(tmp_path / "sub" / "timing.txt") in text

    def test_runs_serially_when_jobs_is_one(
        self, runs: list[Run], tmp_path: Path
    ) -> None:
        """A serial script is still the same script, throttled to one."""
        path = write_local(runs, tmp_path / "run_all.sh", jobs=1)

        assert "JOBS=1" in path.read_text()
        _check_syntax(path)


