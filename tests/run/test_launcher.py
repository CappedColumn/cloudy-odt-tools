class TestWriteSlurmArray:
    """A job-array template plus the manifest its tasks read."""

    def test_is_valid_bash(self, runs: list[Run], tmp_path: Path) -> None:
        _check_syntax(write_slurm_array(runs, tmp_path / "array.sh"))

    def test_placeholders_when_directives_are_omitted(
        self, runs: list[Run], tmp_path: Path
    ) -> None:
        """An obvious blank beats a wrong default: SLURM refuses the script
        until these are filled in."""
        text = write_slurm_array(runs, tmp_path / "array.sh").read_text()

        assert "#SBATCH --account=<ACCOUNT>" in text
        assert "#SBATCH --partition=<PARTITION>" in text
        assert "#SBATCH --time=<TIME>" in text

    def test_directives_are_filled_when_given(
        self, runs: list[Run], tmp_path: Path
    ) -> None:
        path = write_slurm_array(
            runs,
            tmp_path / "array.sh",
            account="krueger",
            partition="notchpeak-freecycle",
            qos="notchpeak-freecycle",
            constraint="rom",
            time="12:00:00",
            mem="8G",
        )
        text = path.read_text()

        assert "#SBATCH --account=krueger" in text
        assert "#SBATCH --partition=notchpeak-freecycle" in text
        assert "#SBATCH --qos=notchpeak-freecycle" in text
        assert "#SBATCH --constraint=rom" in text
        assert "#SBATCH --time=12:00:00" in text
        assert "#SBATCH --mem=8G" in text
        assert "<" not in text.split("\n\n")[0]

    def test_optional_directives_are_absent_when_unset(
        self, runs: list[Run], tmp_path: Path
    ) -> None:
        text = write_slurm_array(runs, tmp_path / "array.sh").read_text()

        assert "--qos" not in text
        assert "--constraint" not in text
        assert "--mem" not in text

    def test_extra_directives_become_dashed_options(
        self, runs: list[Run], tmp_path: Path
    ) -> None:
        text = write_slurm_array(
            runs, tmp_path / "array.sh", mail_type="END"
        ).read_text()

        assert "#SBATCH --mail-type=END" in text

    @pytest.mark.parametrize(
        "runs_per_task, n_tasks, ntasks",
        [(1, 4, 1), (2, 2, 2), (3, 2, 3), (4, 1, 4), (8, 1, 4)],
    )
    def test_manifest_lines_match_runs_per_task(
        self,
        runs: list[Run],
        tmp_path: Path,
        runs_per_task: int,
        n_tasks: int,
        ntasks: int,
    ) -> None:
        path = write_slurm_array(
            runs, tmp_path / "array.sh", runs_per_task=runs_per_task
        )
        manifest = tmp_path / "array_runs.txt"
        lines = manifest.read_text().strip().splitlines()

        assert len(lines) == n_tasks
        assert f"#SBATCH --array=0-{n_tasks - 1}" in path.read_text()
        assert f"#SBATCH --ntasks={ntasks}" in path.read_text()

    def test_manifest_holds_every_run_once(
        self, runs: list[Run], tmp_path: Path
    ) -> None:
        write_slurm_array(runs, tmp_path / "array.sh", runs_per_task=3)
        listed = (tmp_path / "array_runs.txt").read_text().split()

        assert sorted(listed) == sorted(str(r.workdir) for r in runs)
        assert all(Path(d).is_absolute() for d in listed)

    def test_task_reads_its_own_manifest_line(
        self, runs: list[Run], tmp_path: Path
    ) -> None:
        text = write_slurm_array(runs, tmp_path / "array.sh").read_text()

        assert str(tmp_path / "array_runs.txt") in text
        assert 'read -ra RUNS <<< "${TASKS[$SLURM_ARRAY_TASK_ID]}"' in text

    def test_throttle_renders_on_the_array_spec(
        self, runs: list[Run], tmp_path: Path
    ) -> None:
        text = write_slurm_array(
            runs, tmp_path / "array.sh", array_throttle=2
        ).read_text()

        assert "#SBATCH --array=0-3%2" in text

    def test_requeue_is_on_by_default(
        self, runs: list[Run], tmp_path: Path
    ) -> None:
        """Requeue is only safe because of the _DONE guard; the two ship
        together."""
        text = write_slurm_array(runs, tmp_path / "array.sh").read_text()

        assert "#SBATCH --requeue" in text
        assert 'compgen -G "$RUN_DIR/output/*_DONE"' in text

    def test_requeue_can_be_turned_off(
        self, runs: list[Run], tmp_path: Path
    ) -> None:
        text = write_slurm_array(
            runs, tmp_path / "array.sh", requeue=False
        ).read_text()

        assert "--requeue" not in text

    def test_module_line_is_emitted(
        self, runs: list[Run], tmp_path: Path
    ) -> None:
        """The Rome build has no libgfortran RPATH and cannot start
        without this."""
        path = write_slurm_array(
            runs, tmp_path / "array.sh", module="gcc/11.2.0"
        )

        assert "module load gcc/11.2.0" in path.read_text()
        _check_syntax(path)

    def test_job_name_defaults_to_the_script_stem(
        self, runs: list[Run], tmp_path: Path
    ) -> None:
        text = write_slurm_array(runs, tmp_path / "ens42.sh").read_text()

        assert "#SBATCH --job-name=ens42" in text
        assert "#SBATCH --output=" in text

    def test_custom_manifest_path(
        self, runs: list[Run], tmp_path: Path
    ) -> None:
        write_slurm_array(
            runs, tmp_path / "array.sh", manifest=tmp_path / "custom.txt"
        )

        assert (tmp_path / "custom.txt").is_file()

    def test_rejects_a_bad_task_size(
        self, runs: list[Run], tmp_path: Path
    ) -> None:
        with pytest.raises(ValueError, match="at least 1"):
            write_slurm_array(runs, tmp_path / "array.sh", runs_per_task=0)


