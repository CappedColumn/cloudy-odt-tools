class TestRefusals:
    """Cases where generating a script would produce a wrong one."""

    @pytest.mark.parametrize("writer", [write_local, write_slurm_array])
    def test_empty_batch_raises(self, writer, tmp_path: Path) -> None:
        with pytest.raises(ValueError, match="No runs"):
            writer([], tmp_path / "script.sh")

    @pytest.mark.parametrize("writer", [write_local, write_slurm_array])
    def test_mixed_executables_raise(self, writer, tmp_path: Path) -> None:
        """A script names one $EXE, so a mixed batch would silently run
        half of itself with the wrong binary."""
        case = Case()
        case.set(simulation_name="s")
        mixed = [
            Run(case, tmp_path / "CODT_a", tmp_path / "a"),
            Run(case, tmp_path / "CODT_b", tmp_path / "b"),
        ]

        with pytest.raises(ValueError, match="different executables"):
            writer(mixed, tmp_path / "script.sh")


