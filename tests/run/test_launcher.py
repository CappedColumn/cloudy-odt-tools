"""Tests for the launch-script generators.

Two things are being guarded. First, the scripts must be *valid shell* —
they are generated by string assembly, so every test that produces one runs
``bash -n`` over it. Second, nothing in this layer may execute anything:
codt_tools writes a script and the user launches it, which is what keeps the
package free of any knowledge of accounts, partitions or clusters.
"""

from __future__ import annotations

import subprocess
from pathlib import Path

import pytest

from codt_tools.case import Case
from codt_tools.run import Run, launcher, write_local, write_slurm_array


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

def _check_syntax(script: Path) -> None:
    """Fail the test if bash cannot parse the generated script."""
    proc = subprocess.run(
        ["bash", "-n", str(script)],
        capture_output=True,
        text=True,
        check=False,
    )
    assert proc.returncode == 0, (
        f"generated script is not valid bash:\n{proc.stderr}"
    )


@pytest.fixture
def runs(tmp_path: Path) -> list[Run]:
    """Four staged runs sharing one executable."""
    base = Case()
    base.set(simulation_name="sweep")
    cases = base.sweep({"params.tref": [20.0, 21.0, 22.0, 23.0]})
    made = Run.for_cases(cases, tmp_path / "bin" / "CODT", tmp_path / "ens")
    for one in made:
        one.stage()
    return made


