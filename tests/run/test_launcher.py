class TestNothingIsSubmitted:
    """This layer generates text. It does not run schedulers."""

    def test_launcher_imports_no_way_to_execute_anything(self) -> None:
        """The module may *say* sbatch — it writes sbatch scripts — but it
        must not import the machinery to run one."""
        source = Path(launcher.__file__).read_text()

        for forbidden in ("import subprocess", "import os", "Popen",
                          "os.system", "check_call", "check_output"):
            assert forbidden not in source, (
                f"launcher.py should not be able to execute anything, "
                f"found: {forbidden}"
            )

    def test_generating_a_script_touches_no_scheduler(
        self, runs: list[Run], tmp_path: Path, monkeypatch
    ) -> None:
        def _forbidden(*args, **kwargs):
            raise AssertionError(f"launcher executed something: {args}")

        monkeypatch.setattr(subprocess, "run", _forbidden)
        monkeypatch.setattr(subprocess, "Popen", _forbidden)

        write_local(runs, tmp_path / "run_all.sh")
        write_slurm_array(runs, tmp_path / "array.sh")
